# Converts the hand-drawn rider art in art/rider/ into lib/screen/rider_art.h.
# Run after changing the art: python3 scripts/rider_art.py
#
# Each pose is name_1.png and name_2.png (two frames), or name.png when the
# pose has one frame. 48x48, opaque black is ink, fully transparent or white
# is paper. Anything else (grey, half-transparent, wrong size) is an error.
# Standard library only, so it runs without installing anything.

import os
import struct
import sys
import zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ART = os.path.join(ROOT, "art", "rider")
OUT = os.path.join(ROOT, "lib", "screen", "rider_art.h")
SIZE = 48
POSES = ["stopped", "fast", "climbing", "cruising", "bed", "waking", "coffee"]


def read_png(path):
    """Returns rows of (r, g, b, a). 8-bit RGBA or RGB, non-interlaced only."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit(f"{path}: not a PNG")
    pos, idat = 8, b""
    while pos < len(data):
        (n,) = struct.unpack(">I", data[pos:pos + 4])
        kind, chunk = data[pos + 4:pos + 8], data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", chunk)
        elif kind == b"IDAT":
            idat += chunk
    if depth != 8 or color not in (2, 6) or interlace:
        sys.exit(f"{path}: save as 8-bit RGBA, not interlaced")
    bpp = 4 if color == 6 else 3
    raw, stride = zlib.decompress(idat), w * bpp
    prev, rows, p = bytearray(stride), [], 0
    for _ in range(h):
        filt, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if filt == 1:
                line[x] = (line[x] + a) & 255
            elif filt == 2:
                line[x] = (line[x] + b) & 255
            elif filt == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif filt == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x:x + bpp]) + ((255,) if bpp == 3 else ()) for x in range(0, stride, bpp)])
        prev = line
    return w, h, rows


def to_sprite(path):
    w, h, rows = read_png(path)
    if (w, h) != (SIZE, SIZE):
        sys.exit(f"{path}: {w}x{h}, expected {SIZE}x{SIZE}")
    out = []
    for y, row in enumerate(rows):
        line = ""
        for x, (r, g, b, a) in enumerate(row):
            if a == 0 or (a == 255 and (r, g, b) == (255, 255, 255)):
                line += "."
            elif a == 255 and (r, g, b) == (0, 0, 0):
                line += "#"
            else:
                sys.exit(f"{path}: pixel ({x}, {y}) is {(r, g, b, a)}, use only black and transparent")
        out.append(line)
    return out


def array(name, path, sprite):
    lines = [f"// {os.path.relpath(path, ROOT)}", f"static const char *const {name}[RIDER_ROWS] = {{"]
    lines += [f'    "{row}",' for row in sprite]
    return "\n".join(lines + ["};"])


parts = ["// Generated by scripts/rider_art.py from art/rider/. Don't edit by hand.", ""]
for pose in POSES:
    name = pose.upper()
    one = os.path.join(ART, f"{pose}.png")
    if os.path.exists(one):
        parts += [array(name, one, to_sprite(one)), f"#define {name}_2 {name}  // one frame", ""]
        continue
    for frame, suffix in ((1, ""), (2, "_2")):
        path = os.path.join(ART, f"{pose}_{frame}.png")
        if not os.path.exists(path):
            sys.exit(f"missing {path} (or {pose}.png for a one-frame pose)")
        parts += [array(name + suffix, path, to_sprite(path)), ""]

open(OUT, "w").write("\n".join(parts))
print(f"wrote {os.path.relpath(OUT, ROOT)}")
