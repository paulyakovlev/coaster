// Indexed by RiderPose, in enum order
static const char *const *const SPRITES[] = {STOPPED, FAST, CLIMBING, CRUISING,
                                              BED,     WAKING, COFFEE, COUCH};

void screen_draw_rider_scaled(GFXcanvas1 &canvas, int16_t x, int16_t y, RiderPose pose,
                              int16_t scale) {
    canvas.fillRect(x, y, RIDER_COLS * scale, RIDER_ROWS * scale, SCREEN_WHITE);

    const char *const *rows = SPRITES[pose];
    for (int16_t r = 0; r < RIDER_ROWS; r++) {
        for (int16_t c = 0; c < RIDER_COLS; c++) {
            if (rows[r][c] == '#') {
                canvas.fillRect(x + c * scale, y + r * scale, scale, scale, SCREEN_BLACK);
            }
        }
    }
}

void screen_draw_rider(GFXcanvas1 &canvas, int16_t x, int16_t y, RiderPose pose) {
    screen_draw_rider_scaled(canvas, x, y, pose, RIDER_SCALE);
}

void screen_draw_rider_preview(GFXcanvas1 &canvas, RiderPose pose) {
    canvas.fillScreen(SCREEN_WHITE);
    screen_draw_rider(canvas, (SCREEN_WIDTH - RIDER_WIDTH) / 2,
                      (SCREEN_HEIGHT - RIDER_HEIGHT) / 2, pose);
}
